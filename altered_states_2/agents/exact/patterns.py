#!/usr/bin/env python3
"""Exact region re-optimisation via "patterns" + CP-SAT.

With every square outside region R fixed, a state fits iff some PATTERN (a partial
assignment {square in R: letter}) holds. Patterns are generated by a DP over the word:
frontier[(square, alterations)] = set of minimal partial assignments. Entering a free square d
at position i either assigns d = w_i (if d is unassigned), reads d's assigned letter, or spends
the single alteration (d left unconstrained). Sound and complete; dominated (superset)
patterns are dropped.

Then CP-SAT: x[c][L] for c in R (exactly one), pattern p -> its literals, y_s -> OR p,
maximise total population (states with an empty pattern are constant).

    python3 patterns.py GRID CELLS...            # optimise one region exactly
    python3 patterns.py lns GRID --k K --secs T   # random connected regions of K squares
"""
import random
import sys
import time

from ortools.sat.python import cp_model

from model import STATES, NB, LETTERS

POP = {s["code"]: s["pop"] for s in STATES}
SPELL = {s["code"]: s["spell"] for s in STATES}


def minimize(sets):
    sets = sorted(set(sets), key=len)
    out = []
    for p in sets:
        if not any(q <= p for q in out):
            out.append(p)
    return out


def patterns(word, grid, R, cap=20000):
    """Return list of frozensets of (cell, letter); [] if state impossible; [frozenset()] if always."""
    R = set(R)
    front = {}

    def add(nf, key, P):
        nf.setdefault(key, set()).add(P)

    def step(nf, d, a, P, ch):
        if d in R:
            got = dict(P).get(d)
            if got is None:
                add(nf, (d, a), P | {(d, ch)})
                if a == 0:
                    add(nf, (d, 1), P)
            else:
                if got == ch:
                    add(nf, (d, a), P)
                elif a == 0:
                    add(nf, (d, 1), P)
        else:
            if grid[d] == ch:
                add(nf, (d, a), P)
            elif a == 0:
                add(nf, (d, 1), P)

    e = frozenset()
    for c in range(25):
        step(front, c, 0, e, word[0])
    for i in range(1, len(word)):
        # dominance: (c,1,P) dominated by (c,0,Q) with Q<=P
        for key in list(front):
            front[key] = minimize(front[key])
        for (c, a) in list(front):
            if a == 1 and (c, 0) in front:
                zero = front[(c, 0)]
                front[(c, 1)] = [P for P in front[(c, 1)] if not any(Q <= P for Q in zero)]
        tot = sum(len(v) for v in front.values())
        if tot > cap:
            raise OverflowError(tot)
        nf = {}
        for (c, a), Ps in front.items():
            for d in NB[c]:
                for P in Ps:
                    step(nf, d, a, P, word[i])
        front = nf
    allp = []
    for v in front.values():
        allp.extend(v)
    return minimize(allp)


def optimise(grid, R, target=None, timelimit=600, verbose=False, codes=None):
    grid = grid.upper()
    R = sorted(R)
    codes = codes or [s["code"] for s in STATES]
    m = cp_model.CpModel()
    x = {c: {L: m.NewBoolVar(f"x{c}{L}") for L in LETTERS + ["Q"] if L != "Q" or "Q" not in LETTERS}
         for c in R}
    for c in R:
        m.AddExactlyOne(x[c].values())
    const = 0
    terms = []
    npat = 0
    for code in codes:
        pats = patterns(SPELL[code], grid, R)
        if not pats:
            continue
        if any(len(p) == 0 for p in pats):
            const += POP[code]
            continue
        npat += len(pats)
        y = m.NewBoolVar("y" + code)
        pv = []
        for p in pats:
            if len(p) == 1:
                (c, L), = p
                pv.append(x[c][L])
            else:
                v = m.NewBoolVar("")
                for (c, L) in p:
                    m.AddImplication(v, x[c][L])
                pv.append(v)
        m.AddBoolOr(pv).OnlyEnforceIf(y)
        terms.append(POP[code] * y)
    m.Maximize(sum(terms) + const)
    if target is not None:
        m.Add(sum(terms) + const >= target)
    for c in R:
        for L, v in x[c].items():
            m.AddHint(v, int(grid[c] == L))
    s = cp_model.CpSolver()
    s.parameters.num_workers = 1
    s.parameters.max_time_in_seconds = timelimit
    st = s.Solve(m)
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        g = list(grid.lower())
        for c in R:
            for L, v in x[c].items():
                if s.Value(v):
                    g[c] = L.lower()
        return s.StatusName(st), int(round(s.ObjectiveValue())), int(round(s.BestObjectiveBound())), "".join(g), npat, s.WallTime()
    return s.StatusName(st), None, None, None, npat, s.WallTime()


def conn_region(k, rng, seed_cell=None):
    S = {seed_cell if seed_cell is not None else rng.randrange(25)}
    while len(S) < k:
        fr = sorted({d for c in S for d in NB[c]} - S)
        S.add(rng.choice(fr))
    return sorted(S)


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[0] == "lns":
        grid = a[1]
        k = int(a[a.index("--k") + 1]) if "--k" in a else 10
        secs = float(a[a.index("--secs") + 1]) if "--secs" in a else 600
        seed = int(a[a.index("--seed") + 1]) if "--seed" in a else 1
        tl = float(a[a.index("--tl") + 1]) if "--tl" in a else 120
        rng = random.Random(seed)
        from subprocess import check_output
        cur = None
        t0 = time.time()
        it = 0
        while time.time() - t0 < secs:
            R = conn_region(k, rng)
            st, val, bnd, g, npat, wt = optimise(grid, R, timelimit=tl)
            it += 1
            if cur is None:
                cur = val if st == "OPTIMAL" else None
            print(f"it {it} R {R} {st} val {val} bound {bnd} npat {npat} {wt:.1f}s {g}", flush=True)
            if val is not None and g != grid.lower() and cur is not None and val > cur:
                print(f"IMPROVED {val} {g}", flush=True)
                grid, cur = g, val
            elif cur is None and val is not None:
                cur = val
        print("end", cur, grid)
    else:
        grid = a[0]
        R = [int(v) for v in a[1:]]
        t = time.time()
        print(optimise(grid, R, verbose=True), round(time.time() - t, 2))
